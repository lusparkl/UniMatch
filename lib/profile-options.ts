// How official pages name each qualification, written as `key` below produces them. A name covering two
// qualifications ("GCE A-level / International A-level") applies to both. Only names that a page uses for
// the same school-leaving qualification belong here; an unlisted name matches only itself.
const QUALIFICATION_ALIASES: Record<string, string[]> = {
  ib: [IB],
  "international baccalaureate": [IB],
  "international baccalaureate (ib) diploma": [IB],
  gce: [GCE, IAL],
  "gce a-level / international a-level": [GCE, IAL],
  "sat / ap": [US],
  "american curriculum": [US],
  india: [INDIA],
  "indian curricula": [INDIA],
  "indian board exams": [INDIA],
  australia: [ATAR],
  "australian curriculum": [ATAR],
  "new zealand": [NCEA],
  canada: [CANADA],
  "attestat o srednem (polnom) obshchem obrazovanii": [ATTESTAT],
  "chinese mainland jee": [GAOKAO],
  "other overseas qualifications": [OTHER_QUALIFICATION],
  "other high school qualifications": [OTHER_QUALIFICATION],
};
const key = (name: string) =>
  name
    .trim()
    .toLowerCase()
    .replace(/\s*\/\s*/g, " / ")
    .replace(/\s+/g, " ");
const qualifications = (name: string) =>
  QUALIFICATION_ALIASES[key(name)] ?? [key(name)];
/** Whether two names (a rule's and the student's) denote the same qualification. */
export const sameQualification = (a: string, b: string) => {
  const kinds = qualifications(b).map(key);
  return qualifications(a).some((q) => kinds.includes(key(q)));
};

/** The listed spelling of a value typed in any case, or null when it is not on the list. */
export const canonical = (options: readonly string[], value: string) => {
  const v = value.trim().toLowerCase();
  return options.find((o) => o.toLowerCase() === v) ?? null;
};
